package com.multisuperplayer.core.player

import kotlin.math.abs

/**
 * 「按住画面临时加速」用的倍速。
 *
 * ## 为什么是独立的一组档位，而不是复用 [PlaybackSpeedOptions.PRESETS]
 *
 * 两个列表要回答的是**两个不同的问题**：
 * - 常态倍速是「我想用多快的速度看完这部片子」，可以低于 1×（放慢听清台词是有意义的）。
 * - 长按加速是「按住的时候我想多快」，低于 1× 的档位在这里没有意义——按下去反而变慢。
 *
 * 共用一个列表的话，用户在设置里会看到「长按倍速：0.5×」这种没人会选的选项，
 * 而下面那条更糟：两个用途各自的默认值也不同（常态默认 1×，长按默认 2×），
 * 挤在一个列表里就得再解释一遍「哪个是默认」。
 *
 * ## 档位必须落在内核接受的区间内
 *
 * [MAX_PLAYBACK_SPEED] 是 4×，而长按是**直接**把速度下给内核的
 * （见 `PlayerViewModel.setSpeedBoost`），越界的值会被内核夹回去——症状是
 * 「设置里选 8×、按住只有 4×」，只有在真机上按着试才发现。所以档位表的上界
 * 恰好等于内核上界，单测按字面量锁住了这一点。
 */
object SpeedBoostOptions {

    /**
     * 没设置过时用的倍速。
     *
     * 2× 不是随手取的：1.5× 感觉不到「在加速」，3× 以上会开始听不清对白，
     * 而「按住略过一段」这个动作需要的正是「明显更快但仍跟得上」。
     */
    const val DEFAULT = 2f

    /**
     * 可选档位（升序）。
     *
     * 比常态倍速的档位粗很多是有意的：这里要在**零点几秒**内决定「够不够快」，
     * 1.75× 和 2× 的差别在按住的那两秒里根本分不出来，多给档位只会让设置页变长。
     */
    val PRESETS: List<Float> = listOf(1.5f, 2f, 3f, 4f)

    /**
     * 把「设置里存的值」收敛成一个可用档位。
     *
     * 需要收敛的情况比想象的多：键不存在（null）、旧版本或外部工具写过 0（DataStore
     * 缺键读出来是 null，但写进去的 0 和「没设置过」在界面上长得一样）、
     * 被手工改成了 2.5、甚至 NaN。
     *
     * 一律**不抛异常**：这条路径在播放页点一下就会走到，抛出去等于「按住画面就崩」。
     * 认不出来就退回 [DEFAULT]，认得出但不在档位上就取最近档位。
     *
     * 平局（比如 2.5，离 2 和 3 一样远）取**小**的那个：`minBy` 返回第一个最小值，
     * 而列表是升序的。选小的理由是加速这种事「不够快」比「太快听不清」更好纠正
     * ——不够快时用户会再长按一次或去设置里调，听不清则要先怀疑是不是播放器坏了。
     *
     * 注意 ≤ 0 一律当 [DEFAULT]：0 是「缺键」的形状，负数则只能是被写坏的值，
     * 两者都不该被 `minBy` 悄悄映射到 1.5×。
     */
    fun normalize(value: Float?): Float {
        if (value == null || !value.isFinite() || value <= 0f) return DEFAULT
        // 先夹进档位表覆盖的区间，再谈「谁更近」。
        //
        // 不夹的话，`Float.MAX_VALUE` 这类输入是**无法比较**的：`MAX_VALUE - 1.5`
        // 和 `MAX_VALUE - 4` 舍入到同一个数（差距远小于该量级的表示精度），于是
        // 每个候选的距离都相等、`minBy` 返回列表里**第一个**元素——也就是最慢的
        // 1.5×。方向整个反过来，而且不报错。夹一次之后它就只是一次普通的大小比较。
        // 用 `Double` 算距离是顺手把「两个 Float 相减」本身的舍入也排除掉。
        val target = value.coerceIn(PRESETS.first(), PRESETS.last()).toDouble()
        return PRESETS.minBy { abs(it.toDouble() - target) }
    }

    /**
     * 显示用的文案（「2×」）。
     *
     * 复用 [PlaybackSpeedOptions.format] 而不是自己写一遍 `"${value}×"`：
     * 同一个数字在播放页的倍速 chip 上显示「1.5×」、在设置页的长按倍速上显示
     * 「1.5x」是那种「看一眼觉得哪里不对但说不上来」的漂移。
     */
    fun format(value: Float?): String = PlaybackSpeedOptions.format(normalize(value))

    /** 档位里最快的那一档。设置页的说明文案用得到。 */
    val MAX: Float get() = PRESETS.last()
}
